use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;
use std::{env, fs};

const SYSTEMS: &[&str] = &[
    "Nintendo - Super Nintendo Entertainment System",
    // "Nintendo - Game Boy Advance",
    // "Nintendo - Nintendo Entertainment System",
];

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let manifest = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let no_intro = Path::new(&manifest).join("../../submodules/libretro-database/metadat/no-intro");

    let mut out = String::from("// @generated by build.rs! DO NOT EDIT!\n");
    let mut arms = String::new();

    for (i, system) in SYSTEMS.iter().enumerate() {
        let dat = no_intro.join(format!("{system}.dat"));
        println!("cargo:rerun-if-changed={}", dat.display());

        let text = fs::read_to_string(&dat)
            .unwrap_or_else(|e| panic!("failed to read No-Intro DAT {dat:?}: {e}"));

        writeln!(out, "static TABLE_{i}: &[(u32, &str)] = &[").unwrap();
        for (crc, name) in self::parse(&text) {
            writeln!(out, "    ({crc:#010X}, {name:?}),").unwrap();
        }
        out.push_str("];\n");

        writeln!(arms, "        {system:?} => TABLE_{i},").unwrap();
    }

    out.push_str("pub fn titles(libretro_name: &str) -> Option<&'static [(u32, &str)]> {\n");
    out.push_str("    Some(match libretro_name {\n");
    out.push_str(&arms);
    out.push_str("        _ => return None,\n");
    out.push_str("    })\n}\n");

    let dest = Path::new(&env::var("OUT_DIR").unwrap()).join("titles.rs");
    fs::write(dest, out).expect("write generated title tables");
}

fn parse(text: &str) -> BTreeMap<u32, String> {
    let mut titles = BTreeMap::new();
    let mut current: Option<&str> = None;

    for line in text.lines() {
        let line = line.trim_start();
        if let Some(rest) = line.strip_prefix("name \"") {
            current = rest.split('"').next();
        } else if line.starts_with("rom (")
            && let (Some(name), Some(crc)) = (current, self::extract_crc(line))
        {
            titles.entry(crc).or_insert_with(|| name.to_string());
        }
    }

    titles
}

fn extract_crc(line: &str) -> Option<u32> {
    let rest = line.split_once(" crc ")?.1;
    let hex = rest.split_whitespace().next()?;
    u32::from_str_radix(hex, 16).ok()
}
